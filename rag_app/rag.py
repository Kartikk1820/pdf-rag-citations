"""Query pipeline: hybrid retrieve -> grounded decision -> citations -> answer.

Citations are the graded core of this task, so the LLM is never trusted to
produce page numbers. It only decides (a) whether the question is answerable
from the retrieved snippets and (b) which snippet indices it used. The app then
builds each citation from that snippet's stored metadata, so document name and
page number are correct by construction.

The *decision* (answerable? which snippets?) and the *narration* (the prose
shown to the user) are deliberately split into two paths:

- ``answer_question`` -- one LLM call, decision and prose together. Used by
  the CLI, where a fast, cheap, single round-trip matters more than streaming.
- ``stream_answer`` -- the decision call first (so citations are known deter-
  ministically up front), then a second call streamed token-by-token for the
  prose. Used by the web chat UI, where perceived responsiveness matters.

Both share the same retrieval + citation core, so citation behavior is
identical regardless of which path answered the question.

When nothing in the documents clears the relevance bar, ``ENABLE_GENERAL_FALLBACK``
(on by default) routes to one of three explicitly-labeled modes instead of a
flat refusal every time:

- "chitchat" -- casual messages ("hi", "thanks") get a normal conversational
  reply.
- "document_list" -- questions about the document *inventory itself* ("what
  documents do you have", "do you have a chapter 2") are answered directly
  from the real, current index (``vector_store.list_sources()``), never
  generated by the LLM. An LLM asked this with no grounding will confidently
  guess wrong (it has no visibility into what's actually indexed) -- exactly
  the kind of invented-but-plausible answer this whole project exists to
  avoid, so it's treated the same way citations are: looked up, not generated.
- "general" -- genuine off-corpus questions get answered from the model's own
  general knowledge.

None of the three produce citations -- ``mode`` on the result tells the
caller (and the UI) that the answer is NOT grounded in the user's documents,
so the citation guarantee for actual document answers is never blurred with
an ungrounded one.
"""

import re
from dataclasses import dataclass, field
from typing import Iterator

from pydantic import BaseModel, Field

from rag_app import llm, retrieval, vector_store
from rag_app.config import get_settings
from rag_app.prompts import (
    CHITCHAT_NARRATION_SYSTEM_PROMPT,
    FALLBACK_CLASSIFY_SYSTEM_PROMPT,
    FALLBACK_SYSTEM_PROMPT,
    GENERAL_KNOWLEDGE_NARRATION_SYSTEM_PROMPT,
    NARRATION_SYSTEM_PROMPT,
    SYSTEM_PROMPT,
    build_fallback_narration_prompt,
    build_fallback_prompt,
    build_narration_prompt,
    build_user_prompt,
)

UNANSWERABLE_MESSAGE = (
    "The information is not available in the supplied documents."
)

# Cap how many sources we display, keeping citations precise and readable.
_MAX_CITATIONS = 3


class _LLMAnswer(BaseModel):
    is_answerable: bool
    answer: str = ""
    used_chunk_indices: list[int] = Field(default_factory=list)


_VALID_INTENTS = ("chitchat", "document_list", "general")


class _FallbackAnswer(BaseModel):
    intent: str = "general"
    answer: str = ""


class _FallbackClassification(BaseModel):
    intent: str = "general"


@dataclass(frozen=True)
class Citation:
    source: str
    page: int
    snippet: str
    confidence: float = 0.0  # cross-encoder relevance, 0..1


@dataclass(frozen=True)
class Suggestion:
    source: str
    page: int
    confidence: float


@dataclass(frozen=True)
class Answer:
    answered: bool
    text: str
    citations: list[Citation]
    # "grounded" | "chitchat" | "document_list" | "general" | "ambiguous" | "refused"
    mode: str = "grounded"
    suggestions: list[Suggestion] = field(default_factory=list)


@dataclass(frozen=True)
class StreamEvent:
    kind: str  # "citations" | "token" | "done"
    citations: list = field(default_factory=list)
    answered: bool = False
    mode: str = "grounded"
    text: str = ""
    suggestions: list = field(default_factory=list)


def _snippet(text: str, limit: int = 300) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[:limit].rstrip() + "..."


# Matches leaked citation markers like "[0]", "[1, 2]" or " [1,4,6]" that some
# models append to the prose despite the prompt telling them not to.
_INDEX_MARKER = re.compile(r"\s*\[[\d\s,]+\]")


def _clean_answer(text: str) -> str:
    return _INDEX_MARKER.sub("", text).strip()


def _build_citations(cands: list, used_indices: list[int]) -> list[Citation]:
    citations: list[Citation] = []
    seen: set[tuple[str, int]] = set()
    for i in used_indices:
        if not (0 <= i < len(cands)):
            continue
        c = cands[i]
        key = (c.source, c.page)
        if key in seen:
            continue
        seen.add(key)
        citations.append(
            Citation(
                source=c.source,
                page=c.page,
                snippet=_snippet(c.text),
                confidence=c.rerank_score,
            )
        )
        if len(citations) >= _MAX_CITATIONS:
            break

    # If the model answered but named no usable snippet, fall back to the top hit
    # so an answer is never presented without a citation.
    if not citations and cands:
        top = cands[0]
        citations.append(
            Citation(
                source=top.source,
                page=top.page,
                snippet=_snippet(top.text),
                confidence=top.rerank_score,
            )
        )
    return citations


def _build_suggestions(cands: list, limit: int = 5) -> list[Suggestion]:
    """Top distinct documents (one entry per source, best-scoring page) from a
    candidate pool that didn't clear the relevance bar -- used so the app can
    say "did you mean one of these?" instead of guessing or refusing."""
    best_per_source: dict[str, object] = {}
    for c in cands:
        current = best_per_source.get(c.source)
        if current is None or c.rerank_score > current.rerank_score:
            best_per_source[c.source] = c
    ranked = sorted(best_per_source.values(), key=lambda c: c.rerank_score, reverse=True)
    return [
        Suggestion(source=c.source, page=c.page, confidence=c.rerank_score)
        for c in ranked[:limit]
    ]


_AMBIGUOUS_MESSAGE = (
    "I'm not confident which part of your documents this refers to. Did you "
    "mean one of these?"
)


def _detect_named_source(question: str, available: list[str]) -> str | None:
    """If the user names exactly one indexed filename in their message (e.g.
    "2ndChapter.pdf can you summarize this"), treat it as an implicit scope
    filter. The filename string itself never appears in the document's actual
    text, so left in the query it only dilutes retrieval -- it has to be
    recognized and handled explicitly, not just searched for."""
    q_lower = question.lower()
    matches = [s for s in available if s.lower() in q_lower]
    return matches[0] if len(matches) == 1 else None


def _strip_named_source(question: str, source: str) -> str:
    cleaned = re.sub(re.escape(source), "", question, flags=re.IGNORECASE)
    cleaned = cleaned.strip(" ,.-:;")
    return cleaned or question  # never hand retrieval an empty query


def _decide(
    question: str,
    *,
    sources: list[str] | None = None,
    history: list[tuple[str, str]] | None = None,
) -> tuple[list, _LLMAnswer | None, bool]:
    """Runs retrieval + the grounding decision. Returns
    ``(candidates, None, single_source_scoped)`` when nothing clears the
    relevance bar (the grounded LLM call is skipped). ``single_source_scoped``
    tells the caller whether "which document?" is already resolved (Scope UI
    or a named-document match), so it knows whether offering "did you mean
    one of these?" document suggestions would even make sense."""
    settings = get_settings()

    # No explicit Scope filter from the UI, but the user named a document in
    # the message itself -- honor that instead of searching everything and
    # letting the filename text dilute the ranking.
    if sources is None:
        named = _detect_named_source(question, vector_store.list_sources())
        if named:
            sources = [named]
            question = _strip_named_source(question, named)

    single_source_scoped = sources is not None and len(sources) == 1
    cands = retrieval.candidates(question, sources=sources, history=history)
    if not cands:
        return cands, None, single_source_scoped

    # The relevance-score gate exists to decide WHICH document (if any) a
    # question is about, so the app can offer "did you mean one of these?"
    # instead of guessing. Once the search is already scoped to exactly one
    # document -- whether by the Scope UI or by naming it in the message --
    # that question is already answered, and a generic "summarize this
    # document" request will legitimately score low on any single ~800-char
    # chunk (no one chunk IS "the whole document"). In that case, defer to
    # the grounding LLM's own is_answerable judgment instead of the numeric
    # threshold; it still correctly refuses genuinely unrelated questions.
    if not single_source_scoped and max(c.rerank_score for c in cands) < settings.score_threshold:
        return cands, None, single_source_scoped

    user_prompt = build_user_prompt(question, [c.text for c in cands], history)
    result = call_structured_answer(user_prompt)
    if not result.is_answerable or not result.answer.strip():
        return cands, None, single_source_scoped
    return cands, result, single_source_scoped


def _fallback_classify(question: str, history: list[tuple[str, str]] | None) -> str:
    """Classifies into "chitchat" | "document_list" | "general". Defaults to
    "general" (answer from general knowledge) if classification itself fails."""
    try:
        result = llm.call_structured(
            FALLBACK_CLASSIFY_SYSTEM_PROMPT,
            build_fallback_prompt(question, history),
            _FallbackClassification,
            temperature=0.0,
        )
        if result.intent in _VALID_INTENTS:
            return result.intent
    except Exception:
        pass
    return "general"


def _document_list_answer() -> str:
    """Answered by looking up the real index, never generated -- an LLM with
    no visibility into what's actually ingested will otherwise confidently
    guess wrong, which is exactly the failure mode citations are built to
    avoid elsewhere in this pipeline."""
    sources = vector_store.list_sources()
    if not sources:
        return (
            "No documents are indexed yet. Upload a PDF on the Document Library "
            'screen and click "Ingest All".'
        )
    listing = "\n".join(f"- {s}" for s in sources)
    return f"You currently have {len(sources)} document(s) indexed:\n{listing}"


def answer_question(
    question: str,
    *,
    sources: list[str] | None = None,
    history: list[tuple[str, str]] | None = None,
) -> Answer:
    settings = get_settings()
    cands, result, single_source_scoped = _decide(question, sources=sources, history=history)
    if result is not None:
        citations = _build_citations(cands, result.used_chunk_indices)
        return Answer(
            answered=True, text=_clean_answer(result.answer), citations=citations, mode="grounded"
        )

    if not settings.enable_general_fallback:
        return Answer(answered=False, text=UNANSWERABLE_MESSAGE, citations=[], mode="refused")

    fallback = llm.call_structured(
        FALLBACK_SYSTEM_PROMPT,
        build_fallback_prompt(question, history),
        _FallbackAnswer,
        temperature=0.3,
    )
    intent = fallback.intent if fallback.intent in _VALID_INTENTS else "general"
    if intent == "document_list":
        return Answer(answered=True, text=_document_list_answer(), citations=[], mode="document_list")

    # A genuine content question: if retrieval found *something* across
    # MULTIPLE documents, just not confidently enough to answer, offer the
    # closest ones instead of guessing which was meant. Not when already
    # scoped to a single document -- there's nothing left to disambiguate,
    # and suggesting the one document we already searched is nonsensical.
    if intent == "general" and cands and not single_source_scoped:
        return Answer(
            answered=True,
            text=_AMBIGUOUS_MESSAGE,
            citations=[],
            mode="ambiguous",
            suggestions=_build_suggestions(cands),
        )

    return Answer(answered=True, text=fallback.answer.strip(), citations=[], mode=intent)


def stream_answer(
    question: str,
    *,
    sources: list[str] | None = None,
    history: list[tuple[str, str]] | None = None,
) -> Iterator[StreamEvent]:
    """Decision first (citations known up front), then the prose is streamed
    token-by-token from a second, unconstrained (non-JSON) completion."""
    settings = get_settings()
    cands, result, single_source_scoped = _decide(question, sources=sources, history=history)

    if result is not None:
        citations = _build_citations(cands, result.used_chunk_indices)
        used = [cands[i] for i in result.used_chunk_indices if 0 <= i < len(cands)] or cands[:1]
        yield StreamEvent(kind="citations", citations=citations, answered=True, mode="grounded")
        narration_prompt = build_narration_prompt(question, [c.text for c in used], history)
        for token in llm.stream_chat(NARRATION_SYSTEM_PROMPT, narration_prompt):
            yield StreamEvent(kind="token", text=token)
        yield StreamEvent(kind="done")
        return

    if not settings.enable_general_fallback:
        yield StreamEvent(kind="citations", citations=[], answered=False, mode="refused")
        yield StreamEvent(kind="token", text=UNANSWERABLE_MESSAGE)
        yield StreamEvent(kind="done")
        return

    intent = _fallback_classify(question, history)

    if intent == "document_list":
        yield StreamEvent(kind="citations", citations=[], answered=True, mode="document_list")
        yield StreamEvent(kind="token", text=_document_list_answer())
        yield StreamEvent(kind="done")
        return

    # A genuine content question: if retrieval found *something* across
    # MULTIPLE documents, just not confidently enough to answer, offer the
    # closest ones instead of guessing which was meant. Not when already
    # scoped to a single document -- nothing left to disambiguate.
    if intent == "general" and cands and not single_source_scoped:
        yield StreamEvent(
            kind="citations",
            citations=[],
            answered=True,
            mode="ambiguous",
            suggestions=_build_suggestions(cands),
        )
        yield StreamEvent(kind="token", text=_AMBIGUOUS_MESSAGE)
        yield StreamEvent(kind="done")
        return

    system_prompt = CHITCHAT_NARRATION_SYSTEM_PROMPT if intent == "chitchat" else GENERAL_KNOWLEDGE_NARRATION_SYSTEM_PROMPT
    yield StreamEvent(kind="citations", citations=[], answered=True, mode=intent)
    for token in llm.stream_chat(system_prompt, build_fallback_narration_prompt(question, history)):
        yield StreamEvent(kind="token", text=token)
    yield StreamEvent(kind="done")


def call_structured_answer(user_prompt: str) -> _LLMAnswer:
    # temperature=0 for reproducible answers: what you test is what you demo.
    return llm.call_structured(SYSTEM_PROMPT, user_prompt, _LLMAnswer, temperature=0.0)
